// Real Chromium/React controls, synthetic transport only. No credentials or game writes.
const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const root = process.env.MODAGENT_UI_TEST_OUTPUT || path.resolve(__dirname, '../../build/conversation-flow-20260906-r4/ui-smoke')

if (!process.versions.electron) {
  const { buildSync } = require('esbuild')
  const { spawnSync } = require('node:child_process')
  fs.mkdirSync(root, { recursive: true })
  buildSync({ entryPoints: [path.join(__dirname, 'fixtures/conversation-ui.jsx')], bundle: true,
    outfile: path.join(root, 'app.js'), platform: 'browser', format: 'iife',
    alias: { '@edition': path.resolve(__dirname, '../src/edition/free.jsx') },
    loader: { '.png': 'dataurl', '.mp3': 'dataurl' },
    define: { 'import.meta.env': '{}', 'process.env.NODE_ENV': '"test"' },
  })
  const assetDir = process.env.MODAGENT_UI_TEST_ASSETS || path.resolve(root, '../frontend-check/assets')
  const css = fs.readdirSync(assetDir).find(name => name.endsWith('.css'))
  fs.copyFileSync(path.join(assetDir, css), path.join(root, 'style.css'))
  fs.writeFileSync(path.join(root, 'index.html'), '<!doctype html><meta charset="utf-8"><link rel="stylesheet" href="style.css"><body style="background:#101924;color:white"><div style="position:fixed;top:0;right:0;z-index:9999;background:#7b4300">ISOLATED UI TEST — NO REAL INSTALL</div><div id="root"></div><script src="app.js"></script>')
  const result = spawnSync(require('electron'), [__filename], { encoding: 'utf8', timeout: 60000, windowsHide: true })
  process.stdout.write(result.stdout || '')
  process.stderr.write(result.stderr || '')
  if (result.error) throw result.error
  process.exit(result.status || 0)
} else {
  const { app, BrowserWindow, session } = require('electron')
  app.setPath('userData', path.join(root, 'isolated-profile'))
  app.whenReady().then(async () => {
    session.defaultSession.webRequest.onBeforeRequest({ urls: ['http://*/*', 'https://*/*'] }, (_details, callback) => callback({ cancel: true }))
    const win = new BrowserWindow({ show: false, width: 1500, height: 1000, webPreferences: { sandbox: true, contextIsolation: true, nodeIntegration: false, offscreen: true, backgroundThrottling: false } })
    const errors = []
    win.webContents.on('console-message', (_event, level, message) => { if (level >= 3) errors.push(message) })
    await win.loadFile(path.join(root, 'index.html'))
    const result = await win.webContents.executeJavaScript(`(async () => {
      const wait = async (predicate, label) => { for (let n = 0; n < 100; n++) { if (predicate()) return; await new Promise(r => setTimeout(r, 50)) } throw Error('Timed out: ' + label + ' ' + JSON.stringify(window.fixtureRequests) + ' BODY:' + document.body.textContent.slice(-1800)) }
      const button = text => [...document.querySelectorAll('button')].find(b => b.textContent.includes(text))
      const send = async text => {
        await wait(() => document.querySelector('textarea'), 'input')
        const field = document.querySelector('textarea')
        Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype, 'value').set.call(field, text)
        field.dispatchEvent(new Event('input', { bubbles: true }))
        await new Promise(r => setTimeout(r, 80))
        field.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', code: 'Enter', bubbles: true }))
        await new Promise(r => setTimeout(r, 150))
      }
      await send('mod是什么')
      await wait(() => document.body.textContent.includes('是游戏的修改或扩展'), 'answer')
      if (document.body.textContent.includes('已回答本轮问题')) throw Error('Duplicate ordinary task card is visible')
      if (document.querySelectorAll('strong').length !== 1) throw Error('Markdown bold not rendered once')
      await send('帮我搜搜看 界面优化的mod')
      await wait(() => button('生成安装计划'), 'recommendation table')
      if (!document.body.textContent.includes('需求匹配：有功能描述支持')) throw Error('Goal fit evidence absent')
      if (!document.body.textContent.includes('非匹配率')) throw Error('Detail coverage still conflates relevance')
      if (document.body.textContent.includes('来源已返回 0/2') || document.body.textContent.includes('Nexus 详情核验已返回 1/2')) throw Error('Old progress stages accumulated')
      if (document.body.textContent.includes('外部响应较慢')) throw Error('Unproven network diagnosis')
      const check = [...document.querySelectorAll('button')].find(b => b.getAttribute('role') === 'checkbox')
      if (!check) throw Error('Selection checkbox absent')
      check.click()
      await wait(() => !button('生成安装计划').disabled, 'selected target')
      button('生成安装计划').click()
      await wait(() => button('确认下载并安装'), 'confirmation card')
      await wait(() => button('查看待确认清单'), 'linked plan control')
      const beforeJump = window.fixtureRequests.length
      button('查看待确认清单').click()
      if (!document.activeElement?.id?.startsWith('decision-')) throw Error('Plan control did not focus its card')
      if (window.fixtureRequests.length !== beforeJump) throw Error('Opening a plan executed a request')
      if (document.body.textContent.includes('waiting_for_confirmation') || document.body.textContent.includes('confirm_or_adjust_plan')) throw Error('Raw status identifiers visible')
      await send('?何意味')
      await wait(() => document.body.textContent.includes('本轮只解释，不恢复'), 'follow-up answer')
      if (window.fixtureRequests.some(r => r.body.selection_action === 'confirm')) throw Error('Follow-up authorized installation')
      const variant = document.querySelector('select[id^="variant-"]')
      if (!variant) throw Error('Variant selection is missing')
      Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype, 'value').set.call(variant, '42:102')
      variant.dispatchEvent(new Event('change', { bubbles: true }))
      await new Promise(r => setTimeout(r, 100))
      button('确认下载并安装').click()
      await wait(() => document.body.textContent.includes('模拟执行完成'), 'execution summary')
      const confirms = window.fixtureRequests.filter(r => r.body.selection_action === 'confirm')
      if (confirms.length !== 1 || String(confirms[0].body.recommendation_selection[0].file_id) !== '102') throw Error('Chosen file identity lost')
      if (!confirms[0].body.plan_task_id || confirms[0].body.plan_revision_id !== 'plan-' + confirms[0].body.plan_task_id) throw Error('Execution was not bound to the server plan revision')
      await send('模拟中断恢复')
      await wait(() => button('恢复选择并重新核验计划'), 'recovery control')
      button('恢复选择并重新核验计划').click()
      await wait(() => window.fixtureRequests.some(r => r.body.recovery_task_id === 'saved-task'), 'recovery request')
      await wait(() => button('确认下载并安装'), 'recovered confirmation card')
      const restored = window.fixtureRequests.find(r => r.body.recovery_task_id === 'saved-task').body
      if (restored.selection_action !== 'plan' || String(restored.recommendation_selection[0].file_id) !== '102') throw Error('Recovery lost selection or granted execution')
      if (window.fixtureRequests.filter(r => r.body.selection_action === 'confirm').length !== 1) throw Error('Recovery automatically executed')
      const recoveredVariant = [...document.querySelectorAll('select[id^="variant-"]')].at(-1)
      if (recoveredVariant?.value !== '42:102') throw Error('Recovered dropdown reverted to default variant')
      button('确认下载并安装').click()
      await wait(() => window.fixtureRequests.filter(r => r.body.selection_action === 'confirm').length === 2, 'explicit recovery confirmation')
      const recoveredConfirm = window.fixtureRequests.filter(r => r.body.selection_action === 'confirm').at(-1)
      if (String(recoveredConfirm.body.recommendation_selection[0].file_id) !== '102') throw Error('Recovered confirmation changed file identity')
      if (!recoveredConfirm.body.plan_task_id || recoveredConfirm.body.plan_revision_id !== 'plan-' + recoveredConfirm.body.plan_task_id) throw Error('Recovered execution lacked a fresh server plan revision')
      await wait(() => document.body.textContent.includes('确认已提交（历史记录）'), 'historical confirmation resolved')
      if (document.body.textContent.includes('确认入口尚未就绪')) throw Error('Submitted historical plan falsely marked unready')
      return { requests: window.fixtureRequests.filter(r => r.url.endsWith('/chat/stream')).map(r => ({ action: r.body.selection_action, targets: r.body.recommendation_selection })), errors: window.fixtureErrors }
    })()`)
    assert.deepEqual(errors, [], 'renderer errors')
    assert.deepEqual(result.errors, [], 'UI errors')
    fs.writeFileSync(path.join(root, 'ui-result.json'), JSON.stringify(result, null, 2))
    await new Promise(resolve => setTimeout(resolve, 400))
    fs.writeFileSync(path.join(root, 'ui-smoke.png'), (await win.webContents.capturePage()).toPNG())
    console.log('UI FLOW PASSED: answer once -> search -> select -> plan -> variant -> confirm -> summary -> restore selection for read-only plan; no real files installed')
    app.exit(0)
  }).catch(error => { console.error(error); app.exit(1) })
}

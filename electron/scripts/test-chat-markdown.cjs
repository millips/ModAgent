const assert = require('node:assert/strict')
const path = require('node:path')
const Module = require('node:module')
const { buildSync } = require('esbuild')
const React = require('react')
const { renderToStaticMarkup } = require('react-dom/server')
const filename = path.resolve(__dirname, '../src/components/ChatMarkdown.jsx')
const output = buildSync({ entryPoints: [filename], bundle: true, write: false, platform: 'node', format: 'cjs', external: ['react'] })
const compiled = new Module(filename, module)
compiled.filename = filename
compiled.paths = Module._nodeModulePaths(path.dirname(filename))
compiled._compile(output.outputFiles[0].text, filename)
const render = text => renderToStaticMarkup(React.createElement(compiled.exports.default, { text }))
assert.match(render('**Mod** 是什么'), /<strong>Mod<\/strong>/)
assert.match(render('`file.pak`'), /<code[^>]*>file.pak<\/code>/)
assert.match(render('- A\n- B'), /<ul[^>]*><li>A<\/li><li>B<\/li><\/ul>/)
assert.match(render('1. A\n2. B'), /<ol[^>]*><li>A<\/li><li>B<\/li><\/ol>/)
assert.match(render('| 名称 | 状态 |\n| --- | --- |\n| A | **完成** |'), /<table/)
assert.match(render('[source](https://example.com)'), /rel="noopener noreferrer"/)
assert.doesNotMatch(render('[bad](javascript:alert(1))'), /<a /)
assert.doesNotMatch(render('<script>alert(1)</script>'), /<script>/)
assert.doesNotMatch(render('尚未生成安装计划，也没有已安装项目。'), /执行计划|text-cyber-green/)
assert.match(render('```json\n{"x":1}'), /<pre/)
console.log('10 safe Markdown rendering checks passed')

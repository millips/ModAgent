import assert from 'node:assert/strict'
import { updateTaskProgress, upsertProgressMessage } from '../src/components/taskPresentation.mjs'
const first = updateTaskProgress(null, {stage:'source_search', label:'等待 Nexus', label_en:'Waiting for Nexus'}, 'zh-CN', 100, 90)
const heartbeat = updateTaskProgress(first, {stage:'heartbeat', label:'任务仍在进行'}, 'zh-CN', 200, 90)
assert.equal(heartbeat.label, '等待 Nexus')
assert.equal(heartbeat.stageStartedAt, 100)
assert.equal(heartbeat.startedAt, 90)
const next = updateTaskProgress(heartbeat, {stage:'source_detail',label:'核验 1/2'}, 'zh-CN',300,90)
assert.equal(next.stageStartedAt,300)
assert.equal(next.waiting,false)
const en = updateTaskProgress(null,{stage:'search',label:'搜索',label_en:'Searching'},'en',10,5)
assert.equal(en.label,'Searching')
let messages = upsertProgressMessage([], 'task-1', 'search')
messages = upsertProgressMessage(messages, 'task-1', 'detail')
messages = upsertProgressMessage(messages, 'task-1', 'heartbeat', true)
assert.equal(messages.length, 1)
assert.equal(messages[0].content, 'detail')
messages = upsertProgressMessage(messages, 'task-1', 'replayed final stage')
assert.equal(messages.length, 1)
assert.equal(messages[0].content, 'replayed final stage')
console.log('R7 progress reducer: 10 assertions passed')
